	local nLifeAbilityCount = GetActionNum("life");
	for index = 0, nLifeAbilityCount do
	local theAction = EnumAction(index, "life");
	local life_id=theAction:GetID();
	if life_id ~= 0 then
	local name = theAction:GetName()
	if name== "%s" then
	return 1
	end
	end
	end
	return -1
	]], aaa))
	return  tonumber(tem)
end
