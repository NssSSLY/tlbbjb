function CMGraph:Init()
  local vexnum = #self.vexs
  self.dist = {}
  self.path = {}
  for v = 0, vexnum - 1 do
    self.dist[v] = {}
    self.path[v] = {}
    for w = 0, vexnum - 1 do
      local _v = self.vexs[v]
      local _w = self.vexs[w]
      if self.arcs[_v][_w] == nil then
        self.dist[v][w] = self.MAX
        self.path[v][w] = -1
      else
        self.dist[v][w] = self.arcs[_v][_w]
        self.path[v][w] = v
      end
    end
  end
  for u = 0, vexnum - 1 do
    for v = 0, vexnum - 1 do
      for w = 0, vexnum - 1 do
        if v ~= w and self.dist[v][u] + self.dist[u][w] < self.dist[v][w] then
          self.dist[v][w] = self.dist[v][u] + self.dist[u][w]
          self.path[v][w] = self.path[u][w]
        end
      end
    end
  end
end

function CMGraph:LocateVex(x)
  for i = 0, #self.vexs do
    if self.vexs[i] == x then
      return i
    end
  end
  return -1
end

function CMGraph:Print()
  local j = 0
  local a = {}
  local c = 0
  local vexnum = #self.vexs
  for v = 0, vexnum - 1 do
    for w = 0, vexnum - 1 do
      if self.dist[v][w] ~= nil and self.dist[v][w] < self.MAX then
        local str = string.format("顶点[%s]到顶点[%s]的最短路径长为[%d]", self.vexs[v], self.vexs[w], self.dist[v][w])
        j = w
        c = 0
        while -1 ~= self.path[v][j] do
          a[c] = self.path[v][j]
          j = self.path[v][j]
          c = c + 1
        end
        local txt = ""
        for j = c - 1, 0, -1 do
          txt = txt .. self.vexs[a[j]]
          txt = txt .. "->"
        end
        txt = txt .. self.vexs[w]
      end
    end
  end
end

