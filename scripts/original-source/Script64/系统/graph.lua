        end
        if aGetPath then
          local j = w
          local a = {}
          local c = 0
          local last_j = j
          while -1 ~= self.path[v][j] do
            a[c] = self.path[v][j]
            j = self.path[v][j]
            c = c + 1
            if last_j == j then
              break
            end
            last_j = j
            if c > 100 then
              break
            end
          end
          for j = c - 1, 0, -1 do
            path = path .. self.vexs[a[j]]
            path = path .. "-"
          end
          path = path .. self.vexs[w]
        end
        return self.dist[v][w], path
      else
        ShowTipMsg("graph " .. s .. " " .. v .. " " .. d)
      end
    else
      ShowTipMsg("gra22ph " .. s .. " " .. v .. " " .. d)
    end
  end
